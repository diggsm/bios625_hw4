#' lrmodel
#'
#' Generates results from a linear regression model
#'
#' @param formula a linear regression model formula of the format y ~ x. For multivariate linear models, covariates may be added as y ~ x1 + x2 + ...
#' @param data an input dataframe
#' @param weights a vector of weights
#' @return a list of results from the linear regression model, which includes:
#'
#' - Coefficient values
#' - Residual values
#' - Model fitted values
#' - Model rank
#' - Model weights
#' - Model residual dfs
#' - Model call
#' - Model dataframe
#' - The number of observations deleted due to missingness
#'
#' @examples
#' lrmodel(mpg ~ wt, data = mtcars)
#' lrmodel(Sepal.Length ~ Petal.Width, data = iris)$coefficients
#' @export

lrmodel <- function(formula, data, weights = NULL) {
  # Model covariate(s)
  x <- model.matrix.default(formula, data)
  # Model outcome
  y <- model.response(model.frame(formula, data))

  # Model dataframe
  model_df <- model.frame.default(formula, data)

  # Model coefficients
  if (is.null(weights)) {
    coef <- solve(t(x) %*% x) %*% (t(x) %*% y)
  } else {
    # Filter weights vector to rows with complete x and y observations
    w_idx <- !rowSums(is.na(data[, all.vars(formula)]))
    w <- diag(weights[w_idx])
    coef <- solve(t(x) %*% w %*% x) %*% (t(x) %*% w %*% y)
  }

  # Fitted values
  fitted_vals <- x %*% coef

  # Model rank
  rank <- nrow(coef)

  # Residuals
  resid <- y - fitted_vals

  # Residual degrees of freedom
  resid_df <- nrow(x) - rank

  # User call
  user_call <- match.call()

  # Number of observations deleted due to missingness
  n_obs_del <- nrow(data) - nrow(model_df)

  # Store all results in list
  lrmodel_results <- list(
    coefficients = t(coef)[1, ],
    residuals = t(resid)[1, ],
    fitted.values = t(fitted_vals)[1, ],
    rank = rank,
    weights = weights,
    df.residual = resid_df,
    call = user_call,
    model = model_df,
    n_obs_del = n_obs_del
  )

  class(lrmodel_results) <- "lrmodel"

  return(lrmodel_results)

}

#' print.lrmodel
#'
#' The print method for the lrmodel function. Prints a short formatted summary
#' of the linear model results.
#'
#' @param x a linear regression model object generated by lrmodel
#' @param ... additional arguments
#'
#' @export

# Print method for lrmodel()
print.lrmodel <- function(x, ...) {

  # Formatted summary
  cat("Call:\n")
  print(x$call)
  cat("\n")
  cat("Coefficients:\n")
  print(x$coefficients)

  invisible(x)
}
