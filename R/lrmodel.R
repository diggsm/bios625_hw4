#' lrmodel
#'
#' Generates results from a linear regression model
#'
#' @param formula a linear regression model formula of the format y ~ x. For multivariate linear models, covariates may be added as y ~ x1 + x2 + ...
#' @param data an input dataframe
#' @param weights a vector of weights
#' @return a list of results from the linear regression model, which includes:
#'
#' \describe{
#'   \item{coefficients}{Coefficient values}
#'   \item{residuals}{Residual values}
#'   \item{fitted.values}{Model fitted values}
#'   \item{rank}{Model rank}
#'   \item{weights}{Model weights}
#'   \item{df.residual}{Model residual degrees of freedom}
#'   \item{call}{Model call}
#'   \item{terms}{Model formula terms}
#'   \item{model}{Model dataframe}
#'   \item{n_obs_del}{Number of observations deleted due to missingness}
#' }
#'
#' @examples
#' lrmodel(mpg ~ wt, data = mtcars)
#' lrmodel(Sepal.Length ~ Petal.Width, data = iris)$coefficients
#' @export

lrmodel <- function(formula, data, weights = NULL) {
  # Model covariate(s)
  x <- model.matrix.default(formula, data)
  # Model outcome
  y <- model.response(model.frame(formula, data))

  # Check for perfect collinearity among covariate(s)
  if(ncol(x) > 2) {
    cov_mat <- cor(x[, -1], use = "complete.obs")
    diag(cov_mat) <- NA
    is.collinear <- any(cov_mat == 1, na.rm = T)

    if(is.collinear) {
      stop(
        paste(
          "At least 2 of the covariates supplied are perfectly collinear.",
          "Please adjust the model covariates to avoid perfect collinearity",
          "before re-running the model."
        )
      )
    }
  }

  # Model dataframe
  model <- model.frame.default(formula, data)

  # Model coefficients
  if (is.null(weights)) {
    coef <- solve(t(x) %*% x) %*% (t(x) %*% y)
  } else {
    # Filter weights vector to rows with complete x and y observations
    w_idx <- !rowSums(is.na(data[, all.vars(formula)]))
    w <- diag(weights[w_idx])
    coef <- solve(t(x) %*% w %*% x) %*% (t(x) %*% w %*% y)
  }

  coefficients <- t(coef)[1, ]

  # Fitted values
  fitted_vals <- x %*% coef
  fitted.values <- t(fitted_vals)[1, ]

  # Model rank
  rank <- nrow(coef)

  # Residuals
  resid <- y - fitted_vals
  residuals <- t(resid)[1, ]

  # Residual degrees of freedom
  df.residual <- nrow(x) - rank

  # Model call
  call <- match.call()

  # Model formula
  terms = strsplit(as.character(call), split = c("formula =", ","))[[2]]

  # Number of observations deleted due to missingness
  n_obs_del <- nrow(data) - nrow(model)

  # Store all results in list
  lrmodel_results <- list(
    coefficients = coefficients,
    residuals = residuals,
    fitted.values = fitted.values,
    rank = rank,
    weights = weights,
    df.residual = df.residual,
    call = call,
    terms = terms,
    model = model,
    n_obs_del = n_obs_del
  )

  class(lrmodel_results) <- "lrmodel"

  return(lrmodel_results)

}

